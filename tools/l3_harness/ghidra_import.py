def _exports_spec(value: str) -> str:
    module, separator, filename = value.partition("=")
    if not separator or not module.strip() or not filename.strip():
        raise argparse.ArgumentTypeError("expected MODULE=FILE")
    return value


def _xref_spec(value: str) -> dict:
    address, separator, label = value.partition("=")
    try:
        parsed = int(address, 0)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(f"not an address: {value!r}") from exc
    if not 0 <= parsed < ADDRESS_LIMIT:
        raise argparse.ArgumentTypeError(f"address outside 32 bits: {value!r}")
    return {"address": _hex(parsed), "label": label or None}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build a headless Ghidra project from a cerom.py memmap",
        epilog=DEPENDENCY_NOTE,
    )
    parser.add_argument("image", help="firmware image imported as the raw program")
    parser.add_argument("memmap", help="`cerom.py IMG memmap` JSON")
    parser.add_argument("--plan", action="store_true",
                        help="print the commands and block table; run nothing")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--selftest", action="store_true",
                        help="synthetic checks; no Ghidra, no vendor data")
    parser.add_argument("--segment", type=lambda s: int(s, 0), default=0,
                        help="CE segment index in the memmap report (default 0)")
    parser.add_argument("--skip-compressed", action="store_true",
                        help="omit compressed sections instead of failing")
    parser.add_argument("--map-compressed-zero", action="store_true",
                        help="map skipped compressed sections zero-filled "
                             "(implies --skip-compressed)")
    parser.add_argument("--no-ram", action="store_true",
                        help="do not map the ROMHDR RAM window")
    parser.add_argument("--exports", action="append", default=[],
                        type=_exports_spec, metavar="MODULE=FILE",
                        help="`cerom.py exports MODULE` output (repeatable)")
    parser.add_argument("--thunks", metavar="FILE",
                        help="`cerom.py thunks --all --json` output")
    parser.add_argument("--xref", action="append", default=[], type=_xref_spec,
                        metavar="ADDR[=LABEL]",
                        help="report references to this VA after analysis")
    parser.add_argument("--headless", help="path to analyzeHeadless")
    parser.add_argument("--search-root", action="append", default=[],
                        help="extra directory to glob for ghidra* (repeatable)")
    parser.add_argument("--project", dest="project_dir",
                        default="/tmp/opencode/l3-ghidra")
    parser.add_argument("--project-name", default="l3")
    parser.add_argument("--program",
                        help="program name inside the project (default: image name)")
    parser.add_argument("--calling-convention",
                        help="compiler-spec convention name (default: program default)")
    parser.add_argument("--overwrite", action="store_true",
                        help="pass -deleteProject (replace an existing project)")
    parser.add_argument("--analysis-timeout", type=float, default=3600.0,
                        help="seconds for phase 2 analysis (default 3600)")
    parser.add_argument("--report", help=f"report JSON (default: <project>/{REPORT_FILE})")
    return parser


def _load_plan(args, env=None) -> dict:
    try:
        report = load(args.memmap)
    except (OSError, json.JSONDecodeError) as exc:
        raise ImportProblem([f"cannot read {args.memmap}: {exc}"]) from exc

    headless, _ = detect_ghidra(
        explicit=args.headless,
        env=env,
        extra_roots=args.search_root or None,
    )
    return build_plan(
        report,
        image=args.image,
        segment=args.segment,
        skip_compressed=args.skip_compressed,
        map_compressed_zero=args.map_compressed_zero,
        ram=not args.no_ram,
        exports=args.exports,
        thunks=args.thunks,
        xrefs=args.xref,
        headless=headless,
        project_dir=args.project_dir,
        project_name=args.project_name,
        program=args.program,
        overwrite=args.overwrite,
        calling_convention=args.calling_convention,
        analysis_timeout=args.analysis_timeout,
    )


def main(argv=None, env=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--selftest" in argv:
        return selftest()

    parser = build_parser()
    args = parser.parse_args(argv)

    try:
        plan = _load_plan(args, env=env)
    except ImportProblem as exc:
        for problem in exc.problems:
            print(f"error: {problem}", file=sys.stderr)
        print(
            f"RESULT: INVALID ({len(exc.problems)} problem(s))",
            file=sys.stderr,
        )
        return EXIT_INVALID

    if args.plan:
        if args.json:
            print(json.dumps(plan, indent=2))
        else:
            _print_plan(plan)
        return EXIT_OK

    exit_code, report = run_plan(plan, args, env=env)
    report_path = Path(
        args.report
        or str(Path(args.project_dir).expanduser() / REPORT_FILE)
    ).expanduser()
    report["report_path"] = str(report_path)
    try:
        _write_report(report_path, report)
    except OSError as exc:
        print(f"error: cannot write {report_path}: {exc}", file=sys.stderr)

    if args.json:
        print(json.dumps(report, indent=2))
    elif exit_code == EXIT_MISSING_GHIDRA:
        print(GHIDRA_HINT)
        searched = report["ghidra"]["searched"]
        print("searched:")
        for entry in searched:
            print(f"  {entry['source']}: {entry['candidate']}")
        print(f"pyghidra: {report['ghidra']['pyghidra']['detail']}")
        print("RESULT: MISSING_GHIDRA (exit 3)")
    else:
        _print_run(report)
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
