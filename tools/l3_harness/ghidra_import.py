def _print_blocks(plan) -> None:
    for block in plan["blocks"]:
        if block["file_backed"]:
            source = f"file {block['file_offset']}"
        elif block.get("compressed"):
            source = "zero-filled (compressed)"
        else:
            source = "zero-filled"
        print(
            f"  {block['address']} {block['end']} {block['permissions']}  "
            f"{block['name']:<28} {source}"
        )
    if plan.get("ram"):
        ram = plan["ram"]
        print(
            f"  {ram['address']} {ram['end']} {ram['permissions']}  "
            f"{'RAM':<28} zero-filled"
        )
    elif plan.get("ram_note"):
        print(f"  RAM: {plan['ram_note']}")


def _print_labels(plan, limit=40) -> None:
    labels = plan["labels"]
    for label in labels[:limit]:
        ordinal = f" #{label['ordinal']}" if label.get("ordinal") is not None else ""
        target = f" -> {label['target']}" if label.get("target") else ""
        print(
            f"  {label['address']} {label['namespace']}::{label['name']}"
            f" ({label['kind']}{ordinal}){target}"
        )
    if len(labels) > limit:
        print(f"  ... {len(labels) - limit} more label(s)")
    for entry in plan["labels_skipped"][:limit]:
        print(f"  skipped {entry.get('stub_va', '?')}: {entry['reason']}")


def _print_plan(plan) -> None:
    print("Ghidra import plan (nothing is run; no Ghidra result is claimed)")
    print("=" * 72)
    image = plan["image"]
    print(
        f"image      {image['name']}  {image['size']} bytes  "
        f"sha256 {image['sha256']} ({image['sha256_scope']})"
    )
    print(f"processor  {plan['processor']['id']} (verified=false until a run)")
    print(
        f"project    {plan['project']['dir']}  name {plan['project']['name']}  "
        f"program {plan['project']['program']}"
    )
    counts = plan["counts"]
    print(
        f"blocks     {counts['sections']} ({counts['loadable']} file-backed, "
        f"{counts['zero_filled']} zero-filled, "
        f"{counts['skipped_compressed']} compressed skipped)"
    )
    _print_blocks(plan)
    print(
        f"labels     {counts['export_labels']} export, "
        f"{counts['thunk_labels']} thunk, "
        f"{counts['skipped_labels']} skipped"
    )
    _print_labels(plan)
    if plan["xrefs"]:
        print("xrefs      " + ", ".join(item["address"] for item in plan["xrefs"]))
    if plan["skipped"]:
        print("compressed section(s), not mapped as section bytes:")
        for entry in plan["skipped"]:
            print(
                f"  {entry['module']}/{entry['section']} {entry['va']} "
                f"{entry['size']} bytes ({entry['mapped']})"
            )
    print("commands (2 analyzeHeadless invocations):")
    print("  1. " + shlex.join(plan["commands"]["setup"]))
    print("  2. " + shlex.join(plan["commands"]["analyze"]))
    print(f"artifacts  {plan['artifacts']['dir']} (written by a run, not by --plan)")
    print("blockers:")
    if plan["blockers"]:
        for blocker in plan["blockers"]:
            print(f"  - {blocker}")
    else:
        print("  - none")


def _print_run(report) -> None:
    setup_report = (report.get("setup") or {}).get("report") or {}
    analysis = (report.get("analysis") or {}).get("report") or {}
    print(f"ghidra     {report['ghidra']['headless']}")
    print(
        f"blocks     {report['counts']['sections']} planned, "
        f"{len(setup_report.get('blocks', []))} created"
    )
    print(
        f"labels     {analysis.get('labels_applied', 0)}/"
        f"{len(report['labels'])} applied, "
        f"calling convention {analysis.get('calling_convention')}, "
        f"{analysis.get('functions', 0)} function(s)"
    )
    for item in report.get("mismatches", []):
        print(f"MISMATCH {item}")
    for note in report.get("notes", []):
        print(f"NOTE {note}")
    print(f"report     {report.get('report_path')}")
    print(f"RESULT: {report['result']} (exit {report['exit']})")


