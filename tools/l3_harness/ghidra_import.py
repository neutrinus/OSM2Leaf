@contextlib.contextmanager
def no_ghidra_roots():
    saved = runner_mod.DEFAULT_SEARCH_ROOTS
    runner_mod.DEFAULT_SEARCH_ROOTS = ()
    try:
        yield
    finally:
        runner_mod.DEFAULT_SEARCH_ROOTS = saved


def _run_main(argv, env=None):
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer), contextlib.redirect_stderr(buffer):
        code = main(argv, env=env)
    return code, buffer.getvalue()


