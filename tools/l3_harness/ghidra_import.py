class ImportProblem(ValueError):
    """Raised when the memmap, exports or thunks cannot form a valid plan."""

    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__("; ".join(self.problems))


# --------------------------------------------------------------------------
# input helpers
# --------------------------------------------------------------------------


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _int(value, field: str, problems: list[str]) -> int | None:
    if _is_int(value):
        return value
    if isinstance(value, str):
        try:
            return int(value, 0)
        except ValueError:
            problems.append(f"{field}: not an integer: {value!r}")
            return None
    problems.append(f"{field}: missing or not an integer: {value!r}")
    return None


def _hex(value: int) -> str:
    return f"0x{value:x}"


def load(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def permissions_for(characteristics: int) -> str:
    """Same rule as ``rommap.py``: the MEM_* bits, else the content bits."""

    execute = bool(characteristics & 0x20000000)
    read = bool(characteristics & 0x40000000)
    write = bool(characteristics & 0x80000000)
    if not (execute or read or write):
        read = True
        execute = bool(characteristics & 0x00000020)
        write = bool(characteristics & CNT_UNINITIALIZED_DATA)
    return ("r" if read else "-") + ("w" if write else "-") + (
        "x" if execute else "-"
    )


def _split_permissions(value: str) -> tuple[bool, bool, bool]:
    return value[0] == "r", value[1] == "w", value[2] == "x"


_SYMBOL_BAD = re.compile(r"[^A-Za-z0-9_.$@]")
_EXPORT_LINE = re.compile(
    r"^\s*(\d+)\s+(\S+)\s+rva=(0[xX][0-9a-fA-F]+|[0-9a-fA-F]+)\s*$"
)


def symbol_name(name: str) -> str:
    cleaned = _SYMBOL_BAD.sub("_", name.strip())
    if not cleaned:
        cleaned = "_unnamed"
    if cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned


