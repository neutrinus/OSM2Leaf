def detect_ghidra(explicit=None, env=None, extra_roots=None):
    """Thin wrapper over ``runner.detect_ghidra`` (same search order)."""

    return runner_mod.detect_ghidra(
        explicit=explicit, env=env, extra_roots=extra_roots
    )


def probe_pyghidra() -> dict:
    """Lazy hint only; this tool executes through ``analyzeHeadless``."""

    try:
        import pyghidra  # noqa: F401
    except Exception as exc:  # ImportError, or a broken JDK/JPype install
        return {"importable": False, "detail": f"{type(exc).__name__}: {exc}"}
    return {
        "importable": True,
        "detail": "pyghidra imports (not used here: analyzeHeadless is the executor)",
    }


def _run_phase(command, timeout) -> tuple[int, str, str, str | None]:
    try:
        completed = subprocess.run(
            command, capture_output=True, text=True, timeout=timeout
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return EXIT_BLOCKED, "", "", f"{type(exc).__name__}: {exc}"
    return completed.returncode, completed.stdout, completed.stderr, None


def _script_report(path) -> dict | None:
    try:
        document = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return document if isinstance(document, dict) else None


def run_plan(plan, args, env=None) -> tuple[int, dict]:
    """Execute the two phases; return the merged report and exit code."""

    headless, searched = detect_ghidra(
        explicit=args.headless,
        env=env,
        extra_roots=args.search_root or None,
    )
    report = _base_report(plan, "PLAN", EXIT_OK)
    report["ghidra"] = {
        "found": bool(headless),
        "headless": headless,
        "searched": [
            {"source": source, "candidate": candidate} for source, candidate in searched
        ],
        "pyghidra": probe_pyghidra(),
    }

    if not headless:
        report["result"] = "MISSING_GHIDRA"
        report["exit"] = EXIT_MISSING_GHIDRA
        report["notes"].append(
            "no project was created and no import result is claimed"
        )
        return EXIT_MISSING_GHIDRA, report

    image = Path(args.image).expanduser()
    if not image.is_file():
        report["result"] = "BLOCKED"
        report["exit"] = EXIT_BLOCKED
        report["notes"].append(f"firmware image missing: {args.image}")
        return EXIT_BLOCKED, report

    plan["commands"]["setup"][0] = headless
    plan["commands"]["analyze"][0] = headless
    report["commands"] = plan["commands"]

    write_artifacts(plan)

    code, stdout, stderr, failure = _run_phase(
        plan["commands"]["setup"], timeout=1200.0
    )
    report["setup"] = {
        "command": plan["commands"]["setup"],
        "exit": code,
        "stdout": stdout[-4000:],
        "stderr": stderr[-4000:],
        "report": _script_report(plan["artifacts"]["setup_report"]),
    }
    if failure:
        report["setup"]["stderr"] = failure
    if code != EXIT_OK:
        report["result"] = "BLOCKED"
        report["exit"] = EXIT_BLOCKED
        report["notes"].append(f"phase 1 (import + map) exited {code}")
        return EXIT_BLOCKED, report
    if report["setup"]["report"] is None:
        report["result"] = "BLOCKED"
        report["exit"] = EXIT_BLOCKED
        report["notes"].append(
            f"phase 1 wrote no readable report at "
            f"{plan['artifacts']['setup_report']}"
        )
        return EXIT_BLOCKED, report

    code, stdout, stderr, failure = _run_phase(
        plan["commands"]["analyze"], timeout=args.analysis_timeout + 300.0
    )
    report["analysis"] = {
        "command": plan["commands"]["analyze"],
        "exit": code,
        "stdout": stdout[-4000:],
        "stderr": stderr[-4000:],
        "report": _script_report(plan["artifacts"]["analyze_report"]),
    }
    if failure:
        report["analysis"]["stderr"] = failure
    if code != EXIT_OK:
        report["result"] = "BLOCKED"
        report["exit"] = EXIT_BLOCKED
        report["notes"].append(f"phase 2 (analysis + labels) exited {code}")
        return EXIT_BLOCKED, report
    if report["analysis"]["report"] is None:
        report["result"] = "BLOCKED"
        report["exit"] = EXIT_BLOCKED
        report["notes"].append(
            f"phase 2 wrote no readable report at "
            f"{plan['artifacts']['analyze_report']}"
        )
        return EXIT_BLOCKED, report

    setup = report["setup"]["report"]
    analysis = report["analysis"]["report"]
    report["calling_convention"] = {
        "name": analysis.get("calling_convention"),
        "source": plan["calling_convention"]["source"],
        "functions": analysis.get("functions"),
        "changed": analysis.get("calling_convention_changed"),
    }
    report["processor"] = dict(plan["processor"])
    report["processor"]["verified"] = (
        setup.get("language") == plan["processor"]["id"]
    )
    report["export_references"] = analysis.get("export_references", [])
    report["analysis_xrefs"] = analysis.get("xrefs", [])

    mismatches = _compare_readback(plan, setup, analysis)
    report["mismatches"] = mismatches
    if mismatches:
        report["result"] = "MISMATCH"
        report["exit"] = EXIT_MISMATCH
        return EXIT_MISMATCH, report

    report["result"] = "PASS"
    report["exit"] = EXIT_OK
    return EXIT_OK, report


