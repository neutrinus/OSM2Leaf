def _compare_readback(plan, setup: dict, analysis: dict) -> list[str]:
    """Differences between the plan and what the Ghidra scripts read back."""

    problems: list[str] = []

    for entry in setup.get("errors", []):
        problems.append(f"setup: {entry}")
    for entry in analysis.get("errors", []):
        problems.append(f"analysis: {entry}")

    language = setup.get("language")
    if language != plan["processor"]["id"]:
        problems.append(
            f"program language {language!r} != {plan['processor']['id']!r}"
        )

    expected = {}
    for block in plan["blocks"]:
        expected[block["ghidra_name"]] = block
    if plan.get("ram"):
        expected["RAM"] = {
            "address": plan["ram"]["address"],
            "size": plan["ram"]["size"],
            "permissions": plan["ram"]["permissions"],
        }

    observed = {}
    for block in setup.get("blocks", []):
        observed[block["name"]] = block

    for name, wanted in expected.items():
        found = observed.get(name)
        if found is None:
            problems.append(f"block {name}: not created by the setup script")
            continue
        if int(found["address"], 0) != int(wanted["address"], 0):
            problems.append(
                f"block {name}: address {found['address']} != {wanted['address']}"
            )
        if int(found["size"]) != int(wanted["size"]):
            problems.append(f"block {name}: size {found['size']} != {wanted['size']}")
        permissions = (
            ("r" if found["read"] else "-")
            + ("w" if found["write"] else "-")
            + ("x" if found["execute"] else "-")
        )
        if permissions != wanted["permissions"]:
            problems.append(
                f"block {name}: permissions {permissions!r} != "
                f"{wanted['permissions']!r}"
            )
    for name in sorted(set(observed) - set(expected)):
        problems.append(f"unexpected block {name} in the program")

    planned = len(plan["labels"])
    applied = analysis.get("labels_applied")
    if applied != planned:
        problems.append(
            f"labels: {applied} applied, {planned} planned "
            f"({analysis.get('labels_failed', 0)} failed)"
        )
    if not analysis.get("calling_convention"):
        problems.append("calling convention: the program has none")

    return problems


