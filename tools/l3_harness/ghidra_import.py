def _artifact_blocks(plan) -> dict:
    blocks = []
    for block in plan["blocks"]:
        blocks.append(
            {
                "name": block["name"],
                "ghidra_name": block["ghidra_name"],
                "module": block["module"],
                "section": block["section"],
                "address": int(block["address"], 0),
                "size": int(block["size"]),
                "stored_size": int(block["stored_size"]),
                "file_offset": (
                    int(block["file_offset"], 0)
                    if block["file_offset"] is not None
                    else None
                ),
                "file_backed": bool(block["file_backed"]),
                "read": bool(block["read"]),
                "write": bool(block["write"]),
                "execute": bool(block["execute"]),
                "permissions": block["permissions"],
                "characteristics": block["characteristics"],
                "source": block["source"],
            }
        )
    ram = plan.get("ram")
    return {
        "schema": BLOCKS_SCHEMA,
        "generator": GENERATOR,
        "processor": plan["processor"]["id"],
        "image": plan["image"],
        "program": plan["project"]["program"],
        "blocks": blocks,
        "ram": (
            {
                "address": int(ram["address"], 0),
                "size": int(ram["size"]),
                "end": int(ram["end"], 0),
            }
            if ram
            else None
        ),
        "skipped": [
            {
                "module": entry["module"],
                "section": entry["section"],
                "va": entry["va"],
                "size": entry["size"],
                "reason": entry["reason"],
                "mapped": entry["mapped"],
            }
            for entry in plan["skipped"]
        ],
    }


def _artifact_labels(plan) -> dict:
    labels = []
    for label in plan["labels"]:
        entry = {
            "address": int(label["address"], 0),
            "name": label["name"],
            "namespace": label["namespace"],
            "kind": label["kind"],
            "source": label.get("source"),
        }
        for key in ("ordinal", "slot", "target", "confidence", "note"):
            if label.get(key) is not None:
                entry[key] = label[key]
        labels.append(entry)
    return {
        "schema": LABELS_SCHEMA,
        "generator": GENERATOR,
        "image": plan["image"],
        "labels": labels,
        "xrefs": [
            {
                "address": int(item["address"], 0),
                "label": item.get("label"),
            }
            for item in plan.get("xrefs", [])
        ],
    }


def write_artifacts(plan) -> None:
    """Write the scripts, the block/label JSON and keep the plan paths."""

    directory = Path(plan["artifacts"]["dir"])
    directory.mkdir(parents=True, exist_ok=True)
    (directory / SETUP_SCRIPT).write_text(SETUP_SCRIPT_TEXT, encoding="utf-8")
    (directory / ANALYZE_SCRIPT).write_text(ANALYZE_SCRIPT_TEXT, encoding="utf-8")
    (directory / BLOCKS_FILE).write_text(
        json.dumps(_artifact_blocks(plan), indent=2) + "\n", encoding="utf-8"
    )
    (directory / LABELS_FILE).write_text(
        json.dumps(_artifact_labels(plan), indent=2) + "\n", encoding="utf-8"
    )


