def selftest() -> int:
    failures = 0
    for name, func in CHECKS:
        with tempfile.TemporaryDirectory() as tmp:
            try:
                func(tmp)
            except Exception as exc:  # noqa: BLE001 - report, do not abort
                failures += 1
                print(f"FAIL {name}: {exc}")
                if os.environ.get("L3_SELFTEST_VERBOSE"):
                    traceback.print_exc()
            else:
                print(f"ok   {name}")

    print()
    if failures:
        print(f"selftest: FAILED ({failures}/{len(CHECKS)} checks)")
        return EXIT_INVALID
    print(
        f"selftest: OK ({len(CHECKS)} checks, no Ghidra, no vendor data) - "
        "only a real analyzeHeadless run may claim an import"
    )
    return EXIT_OK


