def normalise_report(report, segment=0) -> dict:
    """Turn a ``cerom.py memmap`` document into one ``rommap.py`` report.

    ``cerom.py`` writes ``size`` as ``o32_psize`` (the stored extent) and keeps
    the runtime extent in ``vsize``.  A Ghidra block has to cover the runtime
    extent, otherwise the tail of a ``vsize > psize`` section is unmapped, and
    a BSS section (``psize`` 0) is rejected as zero-sized.  This function
    therefore rewrites ``size`` to ``vsize``, keeps the stored extent in
    ``stored_size`` and lets :func:`rommap.convert` reject everything else.
    """

    problems: list[str] = []
    if not isinstance(report, dict):
        raise ImportProblem(["memmap report must be a JSON object"])
    segments = report.get("segments")
    if not isinstance(segments, list) or not segments:
        raise ImportProblem(["memmap report has no segments"])
    index = _int(segment, "segment", problems)
    if index is None or not 0 <= index < len(segments):
        raise ImportProblem(problems or [f"segment index {segment!r} out of range"])

    selected = segments[index]
    if not isinstance(selected, dict):
        raise ImportProblem([f"segments[{index}] is not an object"])
    modules = selected.get("modules")
    if not isinstance(modules, list) or not modules:
        raise ImportProblem([f"segments[{index}] has no modules"])

    normalised_modules = []
    for module_index, module in enumerate(modules):
        if not isinstance(module, dict):
            problems.append(f"modules[{module_index}] is not an object")
            continue
        name = module.get("name")
        if not isinstance(name, str) or not name:
            problems.append(f"modules[{module_index}]: missing name")
            continue
        sections = module.get("sections")
        if not isinstance(sections, list) or not sections:
            problems.append(f"{name}: no sections")
            continue

        normalised_sections = []
        for section_index, section in enumerate(sections):
            where = f"{name}: sections[{section_index}]"
            if not isinstance(section, dict):
                problems.append(f"{where} is not an object")
                continue
            va = _int(section.get("va", section.get("realaddr")), f"{where}.va",
                      problems)
            stored = _int(
                section.get("stored_size", section.get("psize",
                                                       section.get("size"))),
                f"{where}.stored_size",
                problems,
            )
            virtual = _int(
                section.get("vsize", section.get("size")),
                f"{where}.vsize",
                problems,
            )
            characteristics = _int(
                section.get("characteristics", section.get("flags")),
                f"{where}.characteristics",
                problems,
            )
            if va is None or stored is None or virtual is None:
                continue
            if characteristics is None:
                characteristics = 0
            if virtual <= 0 and stored <= 0:
                problems.append(f"{where}: size must be positive")
                continue
            if stored > virtual > 0:
                problems.append(
                    f"{where}: stored extent {stored} exceeds the runtime "
                    f"extent {virtual}"
                )
                continue
            if stored == 0 and not (
                characteristics & CNT_UNINITIALIZED_DATA
            ) and not section.get("compressed", False):
                problems.append(
                    f"{where}: no stored bytes but not marked uninitialized "
                    f"(characteristics {_hex(characteristics)})"
                )
                continue
            normalised_sections.append(
                {
                    "name": section.get("name", f"sec{section_index}"),
                    "va": _hex(va),
                    "size": virtual if virtual > 0 else stored,
                    "stored_size": stored,
                    "file_offset": section.get("file_offset"),
                    "characteristics": _hex(characteristics),
                    "compressed": section.get("compressed"),
                }
            )
        normalised_modules.append({"name": name, "sections": normalised_sections})

    if problems:
        raise ImportProblem(problems)

    romhdr = selected.get("romhdr") if isinstance(selected.get("romhdr"), dict) else {}
    return {
        "image": report.get("image"),
        "image_size": report.get("image_size"),
        "image_sha256": report.get("image_sha256"),
        "image_sha256_scope": report.get("image_sha256_scope"),
        "segments": [
            {
                "segment_base": selected.get("segment_base"),
                "phys_base": selected.get("phys_base"),
                "pTOC": selected.get("pTOC"),
                "romhdr": romhdr,
                "modules": normalised_modules,
            }
        ],
    }


def _vbases(report, segment=0) -> dict[str, int]:
    """module name -> ``e32_vbase`` from the memmap report (case-sensitive)."""

    result: dict[str, int] = {}
    for module in report["segments"][segment].get("modules", []):
        if not isinstance(module, dict):
            continue
        name = module.get("name")
        vbase = _int(module.get("vbase"), f"{name}.vbase", [])
        if isinstance(name, str) and name and vbase is not None:
            result[name] = vbase
    return result


def _block_from_rommap(block: dict) -> dict:
    address = int(block["address"], 0)
    size = int(block["size"])
    read, write, execute = _split_permissions(block["permissions"])
    return {
        "name": block["name"],
        "module": block["module"],
        "section": block["section"],
        "address": _hex(address),
        "end": _hex(address + size),
        "size": size,
        "stored_size": int(block["stored_size"]),
        "file_offset": block["file_offset"],
        "file_backed": bool(block["file_backed"]),
        "zero_fill": not block["file_backed"],
        "permissions": block["permissions"],
        "read": read,
        "write": write,
        "execute": execute,
        "characteristics": block["characteristics"],
        "source": "section",
    }


def _unique_ghidra_names(blocks) -> None:
    used: set[str] = set()
    for block in blocks:
        base = symbol_name(f"{block['module']}_{block['section']}")
        name = base
        suffix = 2
        while name in used:
            name = f"{base}_{suffix}"
            suffix += 1
        used.add(name)
        block["ghidra_name"] = name


def _in_blocks(address: int, blocks) -> dict | None:
    for block in blocks:
        if int(block["address"], 0) <= address < int(block["end"], 0):
            return block
    return None


def parse_exports(spec, vbases: dict[str, int], problems: list[str]) -> list[dict]:
    """Parse ``MODULE=FILE`` with ``cerom.py exports MODULE`` text lines."""

    module, _, filename = spec.partition("=")
    module, filename = module.strip(), filename.strip()
    if not module or not filename:
        problems.append(f"--exports needs MODULE=FILE, got {spec!r}")
        return []
    canonical = {name.lower(): name for name in vbases}.get(module.lower())
    if canonical is None:
        known = ", ".join(sorted(vbases)[:8]) or "(none)"
        problems.append(
            f"--exports {module}: module is not in the memmap (known: {known})"
        )
        return []
    module = canonical

    try:
        text = Path(filename).read_text(encoding="utf-8")
    except OSError as exc:
        problems.append(f"--exports {module}: cannot read {filename}: {exc}")
        return []

    labels = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = _EXPORT_LINE.match(line)
        if not match:
            problems.append(
                f"--exports {filename}:{number}: not a `cerom.py exports` line: "
                f"{line.strip()!r}"
            )
            continue
        ordinal, name, value = match.groups()
        # `cerom.py exports` prints the RVA as %08x, without the 0x prefix.
        rva = int(value, 0) if value[:2].lower() == "0x" else int(value, 16)
        labels.append(
            {
                "address": _hex(vbases[module] + rva),
                "name": symbol_name(name),
                "namespace": module,
                "kind": "export",
                "ordinal": int(ordinal),
                "source": f"cerom.py exports {module}",
            }
        )
    return labels


def parse_thunks(document, blocks, segment=None) -> tuple[list[dict], list[dict]]:
    """Turn ``cerom.py thunks --json`` into labels; report what was skipped."""

    if isinstance(document, dict):
        records = document.get("stubs")
    else:
        records = document
    if not isinstance(records, list):
        raise ImportProblem(["thunks JSON has no `stubs` list"])

    labels: list[dict] = []
    skipped: list[dict] = []
    seen: set[tuple[int, str]] = set()

    for index, record in enumerate(records):
        if not isinstance(record, dict):
            skipped.append({"index": index, "reason": "not an object"})
            continue
        if segment is not None and record.get("segment") != segment:
            skipped.append(
                {
                    "index": index,
                    "stub_va": record.get("stub_va"),
                    "reason": f"segment {record.get('segment')} != {segment}",
                }
            )
            continue
        stub_va = _int(record.get("stub_va"), f"stubs[{index}].stub_va", [])
        if stub_va is None:
            skipped.append({"index": index, "reason": "no stub_va"})
            continue
        if not 0 <= stub_va < ADDRESS_LIMIT:
            skipped.append(
                {"stub_va": record.get("stub_va"), "reason": "outside 32 bits"}
            )
            continue
        block = _in_blocks(stub_va, blocks)
        if block is None:
            skipped.append(
                {
                    "stub_va": _hex(stub_va),
                    "reason": "stub VA is outside the mapped blocks",
                }
            )
            continue

        owner = record.get("owner") or block["module"]
        target = record.get("module")
        export = record.get("export")
        if record.get("status") == "resolved" and target and export:
            name = symbol_name(f"thunk_{target}_{export}")
            note = None
        else:
            slot = record.get("slot_va") or f"0x{stub_va:x}"
            name = symbol_name(f"thunk_unresolved_{slot}")
            note = record.get("reason") or "unresolved"

        candidate = {
            "address": _hex(stub_va),
            "name": name,
            "namespace": symbol_name(owner),
            "kind": "thunk",
            "slot": record.get("slot_va"),
            "target": f"{target}!{export}" if target and export else None,
            "confidence": record.get("confidence"),
            "note": note,
            "source": "cerom.py thunks",
        }
        key = (stub_va, name)
        if key in seen:
            continue
        seen.add(key)
        labels.append(candidate)

    return labels, skipped


def build_plan(
    report,
    *,
    image=None,
    image_size=None,
    segment=0,
    skip_compressed=False,
    map_compressed_zero=False,
    ram=True,
    exports=(),
    thunks=None,
    xrefs=(),
    headless=None,
    project_dir="/tmp/opencode/l3-ghidra",
    project_name="l3",
    program=None,
    overwrite=False,
    calling_convention=None,
    analysis_timeout=3600.0,
) -> dict:
    """Build the import plan; raises :class:`ImportProblem` on bad inputs."""

    normalised = normalise_report(report, segment=segment)
    skip_compressed = bool(skip_compressed or map_compressed_zero)
    try:
        doc = rommap_mod.convert(
            normalised, segment=0, skip_compressed=skip_compressed
        )
    except rommap_mod.RommapError as exc:
        raise ImportProblem(exc.problems) from exc

    blocks = [_block_from_rommap(block) for block in doc["blocks"]]
    _unique_ghidra_names(blocks)

    skipped = []
    zero_blocks = []
    if map_compressed_zero:
        for entry in doc.get("skipped", []):
            size = int(entry["size"])
            if size <= 0:
                continue
            address = int(entry["va"], 0)
            permissions = permissions_for(int(entry["characteristics"], 0))
            read, write, execute = _split_permissions(permissions)
            zero_blocks.append(
                {
                    "name": f"{entry['module']}/{entry['section']}",
                    "module": entry["module"],
                    "section": entry["section"],
                    "address": _hex(address),
                    "end": _hex(address + size),
                    "size": size,
                    "stored_size": 0,
                    "file_offset": None,
                    "file_backed": False,
                    "zero_fill": True,
                    "permissions": permissions,
                    "read": read,
                    "write": write,
                    "execute": execute,
                    "characteristics": entry["characteristics"],
                    "source": "compressed-zero-fill",
                    "compressed": True,
                }
            )
        _unique_ghidra_names(zero_blocks)
        blocks = sorted(blocks + zero_blocks, key=lambda b: int(b["address"], 0))
        for entry in doc.get("skipped", []):
            skipped.append(dict(entry, mapped="zero-filled"))
        # Re-run the overlap rule over the expanded block set.
        _check_block_overlaps(blocks)
    else:
        skipped = [dict(entry, mapped="omitted") for entry in doc.get("skipped", [])]

    ram_block = None
    ram_note = None
    if ram and isinstance(doc.get("ram"), dict):
        start = int(doc["ram"]["start"], 0)
        end = int(doc["ram"]["end"], 0)
        clash = [
            block
            for block in blocks
            if start < int(block["end"], 0) and int(block["address"], 0) < end
        ]
        if clash:
            ram_note = (
                "not mapped: ROMHDR.ulRAM window "
                f"{_hex(start)}..{_hex(end)} overlaps {clash[0]['name']}"
            )
        elif start < end:
            ram_block = {
                "name": "RAM",
                "address": _hex(start),
                "end": _hex(end),
                "size": end - start,
                "permissions": "rw-",
                "read": True,
                "write": True,
                "execute": False,
                "source": "ROMHDR.ulRAMStart..ulRAMEnd",
                "zero_fill": True,
            }
        else:
            ram_note = f"not mapped: bad window {_hex(start)}..{_hex(end)}"
    elif ram:
        ram_note = "not mapped: the memmap carries no ROMHDR RAM window"

    vbases = _vbases(report, segment=segment)
    problems: list[str] = []
    labels: list[dict] = []
    for spec in exports:
        labels.extend(parse_exports(spec, vbases, problems))

    skipped_labels: list[dict] = []
    if thunks:
        try:
            document = load(thunks)
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"--thunks: cannot read {thunks}: {exc}")
        else:
            thunk_labels, skipped_labels = parse_thunks(
                document, blocks, segment=None
            )
            labels.extend(thunk_labels)

    for label in labels:
        address = int(label["address"], 0)
        if not 0 <= address < ADDRESS_LIMIT:
            problems.append(f"{label['name']}: address outside 32 bits")
            continue
        block = _in_blocks(address, blocks)
        if block is None:
            in_skipped = any(
                int(entry["va"], 0) <= address < int(entry["va"], 0) + int(entry["size"])
                for entry in skipped
            )
            if label["kind"] == "export" and in_skipped:
                problems.append(
                    f"export {label['namespace']}!{label['name']} at "
                    f"{label['address']} lies in a skipped compressed section; "
                    "it cannot be labelled until the CE decompressor exists"
                )
            else:
                problems.append(
                    f"{label['kind']} {label['name']} at {label['address']} is "
                    "outside the mapped blocks"
                )

    if problems:
        raise ImportProblem(problems)

    # Deduplicate identical (address, namespace, name) labels.
    unique: list[dict] = []
    seen: set[tuple[int, str, str]] = set()
    for label in labels:
        key = (
            int(label["address"], 0),
            label.get("namespace") or "",
            label["name"],
        )
        if key in seen:
            continue
        seen.add(key)
        unique.append(label)
    labels = sorted(unique, key=lambda item: int(item["address"], 0))

    script_dir = Path(project_dir).expanduser() / SCRIPT_DIR
    artifacts = {
        "dir": str(script_dir),
        "blocks": str(script_dir / BLOCKS_FILE),
        "labels": str(script_dir / LABELS_FILE),
        "setup_script": str(script_dir / SETUP_SCRIPT),
        "analyze_script": str(script_dir / ANALYZE_SCRIPT),
        "setup_report": str(script_dir / SETUP_REPORT),
        "analyze_report": str(script_dir / ANALYZE_REPORT),
    }
    program_name = program or (Path(image).name if image else "l3-program")
    headless_name = headless or "analyzeHeadless"

    setup_command = [
        headless_name,
        str(Path(project_dir).expanduser()),
        project_name,
    ]
    if overwrite:
        setup_command.append("-deleteProject")
    setup_command += [
        "-import",
        str(image) if image else "<firmware-image>",
        "-processor",
        PROCESSOR_ID,
        "-loader",
        "BinaryLoader",
        "-loader-baseAddr",
        "0x0",
        "-scriptPath",
        artifacts["dir"],
        "-postScript",
        SETUP_SCRIPT,
        artifacts["blocks"],
        artifacts["setup_report"],
        "-noanalysis",
    ]

    analyze_command = [
        headless_name,
        str(Path(project_dir).expanduser()),
        project_name,
        "-process",
        program_name,
        "-scriptPath",
        artifacts["dir"],
        "-postScript",
        ANALYZE_SCRIPT,
        artifacts["labels"],
        artifacts["analyze_report"],
    ]
    if calling_convention:
        analyze_command.append(calling_convention)
    analyze_command += ["-analysisTimeoutPerFile", str(int(analysis_timeout))]

    counts = {
        "sections": len(blocks),
        "loadable": sum(1 for block in blocks if block["file_backed"]),
        "zero_filled": sum(1 for block in blocks if not block["file_backed"]),
        "skipped_compressed": len(skipped),
        "export_labels": sum(1 for label in labels if label["kind"] == "export"),
        "thunk_labels": sum(1 for label in labels if label["kind"] == "thunk"),
        "skipped_labels": len(skipped_labels),
    }

    blockers = []
    if headless is None:
        blockers.append(
            "Ghidra (analyzeHeadless) was not found: --plan only prints the "
            "command; pass --headless or set GHIDRA_INSTALL_DIR to run it"
        )
    if counts["skipped_compressed"]:
        blockers.append(
            f"{counts['skipped_compressed']} compressed section(s) omitted "
            "until the CE decompressor exists (TODO M1.2)"
        )
    if not counts["export_labels"]:
        blockers.append("no exports given: only thunk labels will be applied")
    if not counts["thunk_labels"]:
        blockers.append(
            "no thunk labels: pass `cerom.py thunks --all --json` as --thunks "
            "(M1.6b)"
        )

    return {
        "schema": SCHEMA,
        "generator": GENERATOR,
        "result": "PLAN",
        "pass_claimed": False,
        "image": {
            "name": Path(str(image)).name if image else report.get("image"),
            "size": image_size if image_size is not None else report.get("image_size"),
            "sha256": report.get("image_sha256"),
            "sha256_scope": report.get("image_sha256_scope"),
        },
        "processor": {
            "id": PROCESSOR_ID,
            "verified": PROCESSOR_VERIFIED,
            "source": "rommap.py contract (SuperH:BE:32:SH-4)",
        },
        "project": {
            "dir": str(Path(project_dir).expanduser()),
            "name": project_name,
            "program": program_name,
        },
        "segment": {
            "segment_base": doc.get("source", {}).get("segment_base"),
            "phys_base": doc.get("source", {}).get("phys_base"),
        },
        "blocks": blocks,
        "ram": ram_block,
        "ram_note": ram_note,
        "skipped": skipped,
        "labels": labels,
        "labels_skipped": skipped_labels,
        "counts": counts,
        "calling_convention": {
            "name": calling_convention,
            "source": (
                "program compiler spec"
                if calling_convention is None
                else "explicit --calling-convention"
            ),
        },
        "xrefs": [dict(item) for item in xrefs],
        "commands": {"setup": setup_command, "analyze": analyze_command},
        "artifacts": artifacts,
        "blockers": blockers,
    }


def _check_block_overlaps(blocks) -> None:
    """The same rule as ``rommap.py``, over the final (possibly expanded) set."""

    ordered = sorted(blocks, key=lambda block: int(block["address"], 0))
    for previous, current in zip(ordered, ordered[1:]):
        if int(current["address"], 0) < int(previous["end"], 0):
            raise ImportProblem(
                [
                    "overlapping runtime extents: "
                    f"{previous['name']} [{previous['address']}..{previous['end']}) "
                    f"and {current['name']} "
                    f"[{current['address']}..{current['end']})"
                ]
            )


